"""Generate the 150 board test windows, labels, and golden vectors.
Outputs: exports/common/{test_windows.h,labels.h}, golden/{golden_v1.json,golden_v1.h,test_selection.json}"""
import json
from pathlib import Path
import numpy as np
from data import load_har
from features import quantize, extract, N_FEATURES

ROOT = Path(__file__).resolve().parents[1]
COMMON = ROOT / "exports" / "common"
GOLD = ROOT / "golden"
COMMON.mkdir(parents=True, exist_ok=True)
GOLD.mkdir(exist_ok=True)

SEED, PER_CLASS, N_GOLDEN = 42, 25, 20
COMBOS = [("w128", "r50"), ("w128", "r25"), ("w64", "r50"), ("w64", "r25")]


def write(path, text):
    with open(path, "w", newline="\n") as f:     # always LF
        f.write(text)


def cfloat(v):
    s = f"{float(v):.9g}"
    if not any(c in s for c in ".en"):
        s += ".0"
    return s + "f"


def win_c(w):                                     # (N,3) -> C initializer
    return "{" + ",".join("{%d,%d,%d}" % tuple(r) for r in w) + "}"


# ---- select 150 windows from the held-out subjects: 25 per class, fixed seed, shuffled
d = load_har()
Xq_all, y_all, s_all = quantize(d["Xte"]), d["yte"], d["ste"]
rng = np.random.default_rng(SEED)
sel = np.concatenate([rng.choice(np.where(y_all == k)[0], PER_CLASS, replace=False)
                      for k in range(6)])
rng.shuffle(sel)
Xq, y = Xq_all[sel], y_all[sel]                   # window_idx = position in this list
n = len(sel)

write(GOLD / "test_selection.json", json.dumps(
    {"seed": SEED, "har_test_indices": sel.tolist(), "labels": y.tolist(),
     "subjects": s_all[sel].tolist()}))

# ---- test_windows.h and labels.h
rows = ",\n".join(win_c(w) for w in Xq)
write(COMMON / "test_windows.h",
      "// generated by ml/make_golden.py - do not edit\n#pragma once\n#include <stdint.h>\n"
      f"#define N_TEST_WINDOWS {n}\n#define TEST_WIN_LEN 128\n"
      f"static const int16_t TEST_WINDOWS[N_TEST_WINDOWS][TEST_WIN_LEN][3] = {{\n{rows}\n}};\n")
write(COMMON / "labels.h",
      "// generated by ml/make_golden.py - do not edit\n#pragma once\n#include <stdint.h>\n"
      f"#ifndef N_TEST_WINDOWS\n#define N_TEST_WINDOWS {n}\n#endif\n"
      "// 0 WALKING, 1 UPSTAIRS, 2 DOWNSTAIRS, 3 SITTING, 4 STANDING, 5 LAYING\n"
      f"static const uint8_t TEST_LABELS[N_TEST_WINDOWS] = {{{','.join(map(str, y))}}};\n")

# ---- golden set: 3 per class, then fill to 20, plus 3 synthetic edge cases
pos = []
for k in range(6):
    pos += np.where(y == k)[0][:3].tolist()
pos += [i for i in range(n) if i not in pos][:N_GOLDEN - len(pos)]
g_idx = pos
g_win = [Xq[i] for i in g_idx]
g_lab = [int(y[i]) for i in g_idx]

i = np.arange(128)
const = np.full((128, 3), 500, dtype=np.int16)
alt = np.zeros((128, 3), dtype=np.int16); alt[:, 0] = np.where(i % 2 == 0, 1000, -1000)
tie = np.zeros((128, 3), dtype=np.int16)
tie[:126, 1] = (i[:126] % 3 - 1) * 100            # mean of y is exactly 0, many samples == mean
for w in (const, alt, tie):
    g_idx.append(-1); g_win.append(w); g_lab.append(-1)

G = np.stack(g_win)
feats = {f"{w}_{r}": extract(G, w, r) for w, r in COMBOS}     # (G, 24) float32 each
assert feats["w128_r50"].shape[1] == N_FEATURES

write(GOLD / "golden_v1.json", json.dumps({
    "spec": "docs/feature_spec.md v1", "combo_order": [f"{w}_{r}" for w, r in COMBOS],
    "windows": [{"window_idx": int(a), "label": b, "data": c.tolist(),
                 "features": {k: [float(v) for v in f[j]] for k, f in feats.items()}}
                for j, (a, b, c) in enumerate(zip(g_idx, g_lab, g_win))]}))

ng = len(g_win)
gd = ",\n".join(win_c(w) for w in g_win)
gf = ",\n".join("{" + ",".join("{" + ",".join(cfloat(v) for v in feats[f"{w}_{r}"][j]) + "}"
                               for w, r in COMBOS) + "}" for j in range(ng))
write(GOLD / "golden_v1.h",
      "// generated by ml/make_golden.py - do not edit\n#pragma once\n#include <stdint.h>\n"
      f"#define GOLDEN_N {ng}\n#define GOLDEN_COMBOS 4   // order: w128_r50, w128_r25, w64_r50, w64_r25\n"
      "#define GOLDEN_NFEAT 24\n"
      f"// window_idx into TEST_WINDOWS, or -1 for synthetic edge cases (last 3)\n"
      f"static const int16_t GOLDEN_WINDOW_IDX[GOLDEN_N] = {{{','.join(map(str, g_idx))}}};\n"
      f"static const int16_t GOLDEN_DATA[GOLDEN_N][128][3] = {{\n{gd}\n}};\n"
      f"static const float GOLDEN_FEATS[GOLDEN_N][GOLDEN_COMBOS][GOLDEN_NFEAT] = {{\n{gf}\n}};\n")

# ---- self-check: reload JSON, recompute, compare; check windows match selection
J = json.load(open(GOLD / "golden_v1.json"))
for w in J["windows"]:
    D = np.array(w["data"], dtype=np.int16)
    for (win, rate) in COMBOS:
        got = extract(D, win, rate)[0]
        assert np.array_equal(got, np.array(w["features"][f"{win}_{rate}"], dtype=np.float32))
    if w["window_idx"] >= 0:
        assert np.array_equal(D, Xq[w["window_idx"]])
print(f"{n} test windows, class counts {np.bincount(y).tolist()}, {len(np.unique(s_all[sel]))} subjects")
print(f"golden: {ng} windows ({ng-3} real + 3 edge) x 4 combos x 24 features")
print("edge-case zc (x alt, y tie), w128_r50:",
      feats["w128_r50"][-2][5], feats["w128_r50"][-1][11])
print("ALL GOLDEN CHECKS PASSED")